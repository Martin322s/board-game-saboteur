import { spawnSync, spawn } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const cli = fileURLToPath(new URL('../node_modules/supabase/dist/supabase.js', import.meta.url));
function run(args, capture = false) {
  const result = spawnSync(process.execPath, [cli, ...args], {
    cwd: root, encoding: 'utf8', stdio: capture ? 'pipe' : 'inherit',
  });
  if (result.error) throw result.error;
  if (result.status !== 0) {
    if (capture) console.error(result.stderr);
    throw new Error(`Local Supabase command failed: ${args.join(' ')}`);
  }
  return result.stdout;
}

if (process.argv[2] === 'stop') {
  run(['stop']);
} else {
  run(['start', '-x', 'studio,postgres-meta']);
  // Apply pending migrations even when the persisted stack already exists. Never reset data.
  run(['migration', 'up', '--local']);
  const status = JSON.parse(run(['status', '-o', 'json'], true));
  const url = new URL(status.API_URL);
  if (!['127.0.0.1', 'localhost'].includes(url.hostname) || !status.ANON_KEY)
    throw new Error('Expected a local API URL and browser-safe anonymous key.');
  writeFileSync(new URL('../.env.local', import.meta.url),
    `# Generated by npm run local:start. Local public values only.\nVITE_SUPABASE_URL=${url.origin}\nVITE_SUPABASE_PUBLISHABLE_KEY=${status.ANON_KEY}\n`);
  console.log('Local frontend configured. Start npm run dev in another terminal.');
  // The CLI supplies server-only credentials. JWT verification stays enabled.
  const worker = spawn(process.execPath, [cli, 'functions', 'serve', 'game-command'], {
    cwd: root, stdio: 'inherit',
  });
  process.on('SIGINT', () => worker.kill('SIGINT'));
  process.on('SIGTERM', () => worker.kill('SIGTERM'));
  worker.on('exit', (code) => { process.exitCode = code ?? 0; });
}
